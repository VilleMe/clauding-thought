#!/usr/bin/env python3
"""Scaffold scenarios: what scaffold.py must never do to a project's own files.

A developer check for this repository, not a hook and not copied into projects.
Each scenario builds a throwaway project, runs scaffold.py on it in a subprocess
(which runs the hook self-test inside that project, so nothing touches a real
hook log), and asserts on the files and settings left behind.

    python scripts/scaffoldtest.py

Exit code 1 when any check fails. The 3.4 review found every one of these the
hard way; a scenario is added whenever the scaffold loses something it should
have kept.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCAFFOLD = os.path.join(HERE, "scaffold.py")
ENV = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1", "PYTHONIOENCODING": "utf-8"}
GENERATED_HEADER = "<!-- Generated by Clauding Thought /init -- project-specific delivery checks -->"

results = []
tempdirs = []


def check(cond, label):
    results.append((bool(cond), label))
    print(f"  {'ok ' if cond else 'BAD'} {label}")


def fresh():
    d = tempfile.mkdtemp(prefix="ct-scaffold-")
    tempdirs.append(d)
    for sub in ("scripts", "skills", "tasks"):
        os.makedirs(os.path.join(d, ".claude", sub))
    return d.replace("\\", "/")


def scaffold(project, *args):
    cp = subprocess.run([sys.executable, "-I", SCAFFOLD, "--project", project, *args],
                        capture_output=True, text=True, encoding="utf-8", errors="replace",
                        cwd=project, env=ENV, timeout=600)
    try:
        return json.loads(cp.stdout)
    except ValueError:
        return {"status": "nojson", "error": (cp.stdout + cp.stderr)[-600:], "retired": [], "left_alone": []}


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_bytes(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def load_settings(d):
    return json.loads(read(d + "/.claude/settings.json"))


def hook_commands(settings):
    return [h.get("command") or h.get("type")
            for event in settings.get("hooks", {}).values()
            for entry in event for h in (entry.get("hooks") or [])]


def scenario(title):
    print(f"--- {title} ---")


# ---------------------------------------------------------------------------
scenario("1. settings.json is read before anything is changed")
d = fresh()
write(d + "/.claude/manifest.json", '{"version": "1.1"}')
write_bytes(d + "/.claude/settings.json",
            b'\xef\xbb\xbf{"permissions":{"allow":["Bash(npm test)"]},"env":{"FOO":"1"},"model":"opus"}')
r = scaffold(d, "--update")
s = load_settings(d)
check(r["status"] == "success" and set(s) >= {"permissions", "env", "model", "hooks"},
      f"BOM settings read and kept: keys={sorted(s)}")

write(d + "/.claude/settings.json", '{"permissions": {"allow": ["x"],}')  # trailing comma
write(d + "/.claude/skills/marker.txt", "x")
r = scaffold(d, "--update")
check(r["status"] == "error" and "settings.json" in r.get("error", "") and os.path.isfile(d + "/.claude/skills/marker.txt"),
      f"invalid JSON aborts before touching files: {r.get('error', '')[:60]}")

write(d + "/.claude/settings.json", '{"hooks": {"Stop": [{"matcher": "", "hooks": null}]}}')
r = scaffold(d, "--update")
check(r["status"] in ("success", "warning"), f"null handler list tolerated: {r.get('status')}")

write(d + "/.claude/settings.json", '{"hooks": ["junk"]}')
r = scaffold(d, "--update")
check(r["status"] == "error", f"hooks-as-list aborts: {r.get('error', '')[:70]}")

# ---------------------------------------------------------------------------
scenario("2. ownership: colliding basenames, arguments, retired names, markers")
d = fresh()
write(d + "/.claude/manifest.json",
      '{"version": "1.1", "governance": {"packs": [{"name": "owasp-top-10", "version": "1.0.0", "applied": "2026-01-01"}]}}')
write(d + "/.claude/settings.json", json.dumps({"hooks": {
    "PreToolUse": [
        {"matcher": "Write", "hooks": [{"type": "command", "command": "python tools/secret-filter.py"}]},
        {"matcher": "Write|Edit", "hooks": [
            {"type": "command", "command": "python .claude/scripts/secret-filter.py --strict 2>/dev/null"},
            {"type": "command", "command": "python \"$CLAUDE_PROJECT_DIR/.claude/scripts/my-hook.py\""}]}],
    "UserPromptSubmit": [{"matcher": "", "hooks": [{"type": "command", "command": "python .claude/scripts/skill-reminder.py"}]}],
    "Stop": [{"matcher": "", "hooks": [{"type": "command", "command": "python .claude/scripts/thesis-check.py"}]}]}}))
write(d + "/.claude/scripts/skill-reminder.py", "# my own reminder, nothing to do with the plugin\nprint(1)\n")
write(d + "/.claude/scripts/thesis-check.py",
      '"""Stop hook: verifies the Thesis Demo section on a ready-to-close task. governance.enforcement.thesis_demo"""\n')
write(d + "/.claude/scripts/my-hook.py", "print(1)\n")
write(d + "/.claude/skills/init/SKILL.md", "---\nname: init\n---\n<!-- inspired by Clauding Thought's layout -->\nRun make db-init\n")
write(d + "/.claude/skills/init/helper.sh", "x")
write(d + "/.claude/skills/critique/SKILL.md", "---\nname: critique\n---\nYou are the Clauding Thought Critiquer. harsh.\n")
generated_rule = (f"# Delivery Rules\n{GENERATED_HEADER}\n\n## DELIV-001: Routes register their navigation entry\n"
                  "<!-- severity: error -->\nEvery new route under `src/routes/` adds a menu entry in `src/nav.ts`.\n")
write(d + "/.claude/rules/delivery.md", generated_rule)
os.makedirs(d + "/.git")
r = scaffold(d, "--update")
s = load_settings(d)
cmds = hook_commands(s)
check(any("tools/secret-filter.py" in c for c in cmds), "user hook tools/secret-filter.py kept")
check(sum("scripts/secret-filter.py" in c for c in cmds) == 1, "plugin secret-filter with arguments replaced, not duplicated")
check(any("my-hook.py" in c for c in cmds), "user $CLAUDE_PROJECT_DIR hook kept")
check(not any("thesis-check" in c for c in cmds), "plugin-written thesis-check hook removed")
check(any("skill-reminder" in c for c in cmds) and os.path.isfile(d + "/.claude/scripts/skill-reminder.py"),
      "user-written skill-reminder.py and its registration kept")
check(not os.path.isfile(d + "/.claude/scripts/thesis-check.py"), "plugin-written thesis-check.py deleted")
check(os.path.isfile(d + "/.claude/skills/init/SKILL.md") and os.path.isfile(d + "/.claude/skills/init/helper.sh"),
      "user's own init skill (which mentions the plugin) kept with its helper")
check(not os.path.isfile(d + "/.claude/skills/critique/SKILL.md"), "plugin-written critique skill removed")
check(os.path.isfile(d + "/.claude/rules/delivery.md") and read(d + "/.claude/rules/delivery.md") == generated_rule,
      "rules/delivery.md with the generated header kept unchanged (hydrated rules are project content)")
check(not any(x.startswith("rules/") for x in r["retired"]), f"no rule file reported retired: {r['retired']}")
check(os.path.isfile(d + "/.claude/settings.json.bak"), "settings backup written")
gi = read(d + "/.gitignore")
check(".claude/hook-log*.jsonl" in gi and ".claude/selftest.json" in gi, "gitignore lines appended in a git repo")
check(os.path.isfile(d + "/.claude/packs/owasp-top-10/pack.json"), "applied pack copied for evolve")
check(any("kept" in x for x in r["left_alone"]), f"left_alone reported: {r['left_alone']}")
n1 = len(cmds)
scaffold(d, "--update")
scaffold(d, "--update")
n3 = len(hook_commands(load_settings(d)))
check(n1 == n3, f"three updates idempotent ({n1} handlers)")

# ---------------------------------------------------------------------------
scenario("3. a project-authored file under a retired rule name survives an update")
d = fresh()
write(d + "/.claude/manifest.json", '{"version": "1.1"}')
own_rule = ("---\npaths:\n  - \"src/**\"\n---\n# Delivery\n\nRules for delivery of a feature: the delivery checklist "
            "lives here, not in a ticket.\n\n## DELIV-001: Feature flags default off\n<!-- severity: error -->\n"
            "A new flag in `config/flags.ts` ships disabled.\n\n## DELIV-004: Migrations ship with a down step\n"
            "<!-- severity: warning -->\nEvery file under `db/migrations/` defines `down()`.\n")
write(d + "/.claude/rules/delivery.md", own_rule)
write(d + "/.claude/rules/architecture.md", "---\npaths:\n  - \"src/**\"\n---\n# Architecture\n\nARCH-001: handlers never import the database layer.\n")
r = scaffold(d, "--update")
check(r["status"] == "success", f"update succeeds: {r.get('status')}")
check(os.path.isfile(d + "/.claude/rules/delivery.md") and read(d + "/.claude/rules/delivery.md") == own_rule,
      "project-authored rules/delivery.md (no generated header, contains the word delivery) kept byte for byte")
check(read(d + "/.claude/rules/architecture.md").startswith("---\npaths:"), "other rule files untouched")
check("rules/delivery.md" not in r["retired"] and not any("delivery" in x for x in r["left_alone"]),
      "a rule file is neither retired nor reported as left alone; it is simply the project's")

# ---------------------------------------------------------------------------
scenario("4. disabled_hooks and llm_judge")
d = fresh()
write(d + "/.claude/manifest.json",
      '{"version": "1.1", "governance": {"disabled_hooks": ["claim-guard", "nonsense"]}, "verification": {"llm_judge": true}}')
r = scaffold(d, "--update")
cmds = hook_commands(load_settings(d))
check(not any("claim-guard" in c for c in cmds) and "prompt" in cmds, "claim-guard not registered, prompt judge registered")
check(r.get("unknown_disabled_hooks") == ["nonsense"], "unknown disabled hook reported")
check(r.get("selftest", {}).get("status") == "pass",
      f"self-test {r.get('selftest', {}).get('passed')}/{r.get('selftest', {}).get('total')} with a disabled hook")

# ---------------------------------------------------------------------------
scenario("5. full scaffold on an empty project")
d = fresh()
shutil.rmtree(d + "/.claude")
r = scaffold(d)
st = r.get("selftest", {})
check(r["status"] == "success" and st.get("status") == "pass",
      f"full scaffold: self-test {st.get('passed')}/{st.get('total')} failed={st.get('failed')}")
check(not os.path.isfile(d + "/.gitignore"), "no gitignore created in a folder that is not a git repo")

# ---------------------------------------------------------------------------
for t in tempdirs:
    shutil.rmtree(t, ignore_errors=True)
bad = [label for ok, label in results if not ok]
print(f"\n{len(results) - len(bad)} of {len(results)} checks passed" + (f"; FAILED: {bad}" if bad else ""))
sys.exit(1 if bad else 0)
