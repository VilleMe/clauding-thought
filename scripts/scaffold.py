#!/usr/bin/env python3
"""Scaffolds the .claude/ governance directory for a project.

Creates the directory tree, copies the hook scripts, merges the governance
hooks into .claude/settings.json, retires files from older plugin versions
that the plugin itself wrote, creates stub files, and runs the hook self-test.
Run by the plugin's init skill (/clauding-thought:init) before the analysis phase.

Usage:
  python scaffold.py [--project DIR]           # Full scaffold for a new project
  python scaffold.py --update [--project DIR]  # Refresh scripts and hooks only

The project is --project, else $CLAUDE_PROJECT_DIR, else the current directory.

Safety: settings.json and manifest.json are read and validated BEFORE
anything is copied, deleted or written. An unreadable settings.json aborts
the run with an error instead of being replaced. A backup of settings.json
is written next to it before every rewrite. Only files the plugin wrote
(recognised by their own text) are ever retired.

Output: JSON with status, paths, what was created, what remains for the
agent, and the self-test summary.
"""
import json
import os
import re
import shlex
import shutil
import subprocess
import sys

# Scripts copied into <project>/.claude/scripts/: hooks, their helpers, and the
# tool scripts generated skills call (project skills cannot reach the plugin root).
HOOK_SCRIPTS = [
    "secret-filter.py",
    "destructive-guard.py",
    "scope-guard.py",
    "anti-rationalization.py",
    "evidence-check.py",
    "claim-guard.py",
    "hook_telemetry.py",
    "task_doc.py",
    "transcript.py",
    "complexity.py",
    "report_data.py",
]

# Scripts whose hook registrations this plugin owns (by script file name under .claude/scripts/).
PLUGIN_HOOK_SCRIPTS = {
    "secret-filter.py", "destructive-guard.py", "scope-guard.py",
    "anti-rationalization.py", "evidence-check.py", "claim-guard.py",
}
HOOK_NAMES = {s[:-3] for s in PLUGIN_HOOK_SCRIPTS}

# Scripts older plugin versions installed and this version no longer ships.
# A file is deleted only when its text shows the plugin wrote it.
RETIRED_SCRIPTS = {"skill-reminder.py", "rule-context.py", "deferral-check.py", "thesis-check.py", "setup-user-dir.py"}
PLUGIN_SCRIPT_MARKERS = ("Clauding Thought", "clauding-thought", "governance.enforcement", "governance skills",
                         "Thesis Demo", "deferred-item ledger", "re-emphasize relevant rules")

# Project-local skills and rule files older plugin versions copied in, with the
# text the plugin wrote into them. Only a file carrying its marker is removed.
RETIRED_PROJECT_SKILLS = {
    "init": ("# Clauding Thought — Init Instructions", "# Clauding Thought: Init", "Clauding Thought — Full Init"),
    "report": ("You are the Clauding Thought Report agent",),
    "export": ("You are the Clauding Thought Export agent",),
    "insights": ("You are the Clauding Thought Insights agent",),
    "critique": ("You are the Clauding Thought Critiquer",),
    "thesis": ("You are the Thesis Demo author",),
}
RETIRED_RULE_FILES = {"delivery.md": ("Generated by Clauding Thought", "delivery")}

GENERATED_SKILLS = ["preflight", "qc", "qc-fix", "evolve", "task-doc", "close-task"]

LLM_JUDGE_MARKER = "[clauding-thought llm-judge]"
LLM_JUDGE_PROMPT = (
    LLM_JUDGE_MARKER + " You are reviewing the final message of a coding-agent turn. "
    "Input: $ARGUMENTS. Answer ok=false only if the message (1) dismisses a problem "
    "it found with phrases like out of scope, pre-existing, acceptable tradeoff, "
    "without committing to fix or track it, or (2) asserts a fact about data, "
    "records, or system state as verified or correct while the message quotes no "
    "command output or query result that shows it. Quoted or fenced text does not "
    "count as the message's own claim. Otherwise ok=true. In reason, quote the "
    "sentence and say what evidence or commitment is missing."
)

GITIGNORE_LINES = [".claude/hook-log*.jsonl", ".claude/selftest.json", ".claude/settings.json.bak"]


# --------------------------------------------------------------------------
# Reading and validating inputs
# --------------------------------------------------------------------------

def read_text(path):
    with open(path, "rb") as f:
        raw = f.read()
    if raw.startswith(b"\xef\xbb\xbf"):
        return raw[3:].decode("utf-8", "replace")
    return raw.decode("utf-8", "replace")


def load_json_file(path):
    """(data, error). data is {} when the file is missing; error names a parse problem."""
    if not os.path.isfile(path):
        return {}, None
    try:
        data = json.loads(read_text(path))
    except ValueError as e:
        return None, f"{os.path.basename(path)} is not valid JSON ({e})"
    if not isinstance(data, dict):
        return None, f"{os.path.basename(path)} must contain a JSON object"
    return data, None


def validate_hooks_shape(hooks):
    """Return an error string when the hooks block has a shape merge_hooks cannot keep safely."""
    if hooks is None:
        return None
    if not isinstance(hooks, dict):
        return "settings.json: 'hooks' must be an object keyed by event name"
    for event, entries in hooks.items():
        if not isinstance(entries, list):
            return f"settings.json: hooks.{event} must be a list"
        for entry in entries:
            if not isinstance(entry, dict):
                return f"settings.json: an entry under hooks.{event} is not an object"
            handlers = entry.get("hooks")
            if handlers is not None and not isinstance(handlers, list):
                return f"settings.json: 'hooks' inside an entry under hooks.{event} must be a list"
            for h in handlers or []:
                if not isinstance(h, dict):
                    return f"settings.json: a handler under hooks.{event} is not an object"
    return None


# --------------------------------------------------------------------------
# Hook ownership and merging
# --------------------------------------------------------------------------

def hook_script_name(hook):
    """File name of the script a command hook runs from `.claude/scripts/`, else ''.

    Scans every token (so a command with arguments still counts) and accepts
    `$CLAUDE_PROJECT_DIR/.claude/scripts/x.py`, quoted forms and backslashes.
    """
    cmd = hook.get("command", "") if isinstance(hook, dict) else ""
    if not isinstance(cmd, str) or not cmd.strip():
        return ""
    try:
        tokens = shlex.split(cmd, posix=True)
    except ValueError:
        tokens = cmd.split()
    for tok in tokens:
        t = tok.replace("\\", "/")
        t = re.sub(r"^\$\{?CLAUDE_PROJECT_DIR\}?/", "", t)
        m = re.search(r"(?:^|/)\.claude/scripts/([^/]+)$", t)
        if m:
            return m.group(1)
    return ""


def is_plugin_hook(hook, retired_owned=frozenset()):
    """True for the plugin's current hooks, its prompt judge, and registrations
    of retired scripts that the plugin itself wrote (or that no longer exist)."""
    if not isinstance(hook, dict):
        return False
    if hook.get("type") == "prompt":
        return str(hook.get("prompt", "")).startswith(LLM_JUDGE_MARKER)
    name = hook_script_name(hook)
    return name in PLUGIN_HOOK_SCRIPTS or name in retired_owned


def python_command():
    return "python" if sys.platform.startswith("win") else "python3"


def plugin_hooks(py, disabled=(), llm_judge=False):
    def cmd(script):
        return {"type": "command", "command": f"{py} .claude/scripts/{script}"}

    def wanted(script):
        return script[:-3] not in disabled

    file_hooks = [cmd(s) for s in ("secret-filter.py", "scope-guard.py") if wanted(s)]
    bash_hooks = [cmd("destructive-guard.py")] if wanted("destructive-guard.py") else []
    stop_hooks = [cmd(s) for s in ("anti-rationalization.py", "evidence-check.py", "claim-guard.py") if wanted(s)]
    if llm_judge:
        stop_hooks.append({"type": "prompt", "prompt": LLM_JUDGE_PROMPT, "timeout": 30})
    out = {"PreToolUse": [], "Stop": []}
    if file_hooks:
        out["PreToolUse"].append({"matcher": "Write|Edit|MultiEdit|NotebookEdit", "hooks": file_hooks})
    if bash_hooks:
        out["PreToolUse"].append({"matcher": "Bash", "hooks": bash_hooks})
    if stop_hooks:
        out["Stop"].append({"matcher": "", "hooks": stop_hooks})
    return {k: v for k, v in out.items() if v}


def merge_hooks(existing, ours, retired_owned=frozenset()):
    """Replace this plugin's hooks in `existing`, keep everything else.

    Only handlers whose command runs one of the plugin's current scripts from
    `.claude/scripts/`, a retired script the plugin wrote, or the plugin's
    prompt judge are removed. A project's own hooks survive, even in the same
    entry and even under a retired name. Events left empty are dropped.
    """
    merged = dict(existing or {})
    for event in set(merged) | set(ours):
        kept = []
        for entry in merged.get(event, []) or []:
            remaining = [h for h in (entry.get("hooks") or []) if not is_plugin_hook(h, retired_owned)]
            if remaining:
                kept.append({**entry, "hooks": remaining})
        merged[event] = kept + ours.get(event, [])
        if not merged[event]:
            del merged[event]
    return merged


# --------------------------------------------------------------------------
# Retirement with ownership checks
# --------------------------------------------------------------------------

def file_has_marker(path, markers, limit=4000):
    try:
        head = read_text(path)[:limit]
    except OSError:
        return False
    return any(m in head for m in markers)


def skill_text_mentions(claude_dir, skill, needle):
    path = os.path.join(claude_dir, "skills", skill, "SKILL.md")
    if not os.path.isfile(path):
        return None
    try:
        return needle.lower() in read_text(path).lower()
    except OSError:
        return None


def run_selftest(plugin_root, project_root):
    script = os.path.join(plugin_root, "scripts", "selftest.py")
    if not os.path.isfile(script):
        return {"status": "missing"}
    try:
        env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
        cp = subprocess.run([sys.executable, script, "--project", project_root, "--json"],
                            capture_output=True, text=True, timeout=300, encoding="utf-8", errors="replace", env=env)
        report = json.loads(cp.stdout) if cp.stdout.strip() else {}
        failed = [r["name"] for r in report.get("results", []) if not r.get("ok")]
        return {"status": report.get("status", "error"), "passed": report.get("passed"),
                "total": report.get("total"), "failed": failed[:12],
                "result_file": os.path.join(project_root, ".claude", "selftest.json")}
    except (OSError, ValueError, subprocess.SubprocessError) as e:
        return {"status": "error", "error": str(e)[:300]}


def resolve_plugin_root():
    root = os.environ.get("CLAUDE_PLUGIN_ROOT", "")
    if not root or not os.path.isdir(root):
        skill_dir = os.environ.get("CLAUDE_SKILL_DIR", "")
        if skill_dir:
            root = os.path.normpath(os.path.join(skill_dir, "..", ".."))
    if not root or not os.path.isdir(root):
        root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    return root if os.path.isdir(os.path.join(root, "scripts")) else ""


def fail(message, **extra):
    print(json.dumps({"status": "error", "error": message, **extra}, indent=2))
    sys.exit(1)


try:
    plugin_root = resolve_plugin_root()
    if not plugin_root:
        fail("Cannot resolve the plugin root directory",
             CLAUDE_PLUGIN_ROOT=os.environ.get("CLAUDE_PLUGIN_ROOT", "(not set)"))

    update_mode = "--update" in sys.argv
    project_root = None
    if "--project" in sys.argv:
        idx = sys.argv.index("--project")
        if idx + 1 < len(sys.argv):
            project_root = sys.argv[idx + 1]
    project_root = os.path.abspath(project_root or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
    claude_dir = os.path.join(project_root, ".claude")

    plugin_version = (load_json_file(os.path.join(plugin_root, ".claude-plugin", "plugin.json"))[0] or {}).get("version", "unknown")

    # --- 0. Read and validate every input before touching anything ---
    manifest_path = os.path.join(claude_dir, "manifest.json")
    manifest, manifest_error = load_json_file(manifest_path)
    if update_mode and not os.path.isfile(manifest_path):
        fail("No .claude/manifest.json found. Run a full init first.")
    if manifest_error:
        fail(manifest_error, hint="Fix .claude/manifest.json; nothing was changed.")
    manifest = manifest or {}

    settings_path = os.path.join(claude_dir, "settings.json")
    settings, settings_error = load_json_file(settings_path)
    if settings_error:
        fail(settings_error, hint="Fix or move aside .claude/settings.json; nothing was changed. "
                                  "The scaffold never replaces a settings file it cannot read.")
    settings = settings or {}
    shape_error = validate_hooks_shape(settings.get("hooks"))
    if shape_error:
        fail(shape_error, hint="Repair the hooks block by hand; nothing was changed.")

    governance = manifest.get("governance") or {}
    disabled = {str(h) for h in (governance.get("disabled_hooks") or []) if isinstance(h, str)}
    unknown_disabled = sorted(disabled - HOOK_NAMES)
    disabled &= HOOK_NAMES
    llm_judge = bool((manifest.get("verification") or {}).get("llm_judge"))

    # --- 1. Directory tree ---
    for d in ["skills/" + s for s in GENERATED_SKILLS] + ["agents", "rules", "patterns", "tasks", "scripts"]:
        os.makedirs(os.path.join(claude_dir, d), exist_ok=True)

    # --- 2. Files copied next to generated skills ---
    copied = []
    src = os.path.join(plugin_root, "templates", "evolve", "changelog-spec.md")
    dst = os.path.join(claude_dir, "skills", "evolve", "changelog-spec.md")
    if os.path.isfile(src):
        shutil.copy2(src, dst)
        copied.append("skills/evolve/changelog-spec.md")

    # --- 3. Hook and tool scripts ---
    copied_scripts = []
    for script in HOOK_SCRIPTS:
        s = os.path.join(plugin_root, "scripts", script)
        d = os.path.join(claude_dir, "scripts", script)
        if os.path.isfile(s):
            shutil.copy2(s, d)
            copied_scripts.append(script)

    # --- 4. Retire what the plugin itself wrote in earlier versions ---
    retired = []
    left_alone = []
    retired_owned = set()  # retired script names whose registrations may be stripped
    for script in sorted(RETIRED_SCRIPTS):
        path = os.path.join(claude_dir, "scripts", script)
        if os.path.isfile(path):
            if file_has_marker(path, PLUGIN_SCRIPT_MARKERS):
                os.remove(path)
                retired.append(f"scripts/{script}")
                retired_owned.add(script)
            else:
                left_alone.append(f"scripts/{script} (not written by the plugin; kept)")
        else:
            retired_owned.add(script)  # registered but absent: a stale registration
    for skill, markers in RETIRED_PROJECT_SKILLS.items():
        skill_dir = os.path.join(claude_dir, "skills", skill)
        skill_md = os.path.join(skill_dir, "SKILL.md")
        if os.path.isfile(skill_md):
            if file_has_marker(skill_md, markers, limit=20000):
                os.remove(skill_md)
                for extra in ("manifest.schema.json",):
                    p = os.path.join(skill_dir, extra)
                    if os.path.isfile(p):
                        os.remove(p)
                try:
                    os.rmdir(skill_dir)  # only when nothing else is in it
                except OSError:
                    pass
                retired.append(f"skills/{skill}")
            else:
                left_alone.append(f"skills/{skill} (not written by the plugin; kept)")
    for rule, markers in RETIRED_RULE_FILES.items():
        path = os.path.join(claude_dir, "rules", rule)
        if os.path.isfile(path) and file_has_marker(path, markers):
            os.remove(path)
            retired.append(f"rules/{rule}")
    for stale in (".plugin-root",):
        path = os.path.join(claude_dir, stale)
        if os.path.isfile(path):
            os.remove(path)
            retired.append(stale)

    # --- 5. settings.json: hooks only, with a backup first ---
    if os.path.isfile(settings_path):
        shutil.copy2(settings_path, settings_path + ".bak")
    settings["hooks"] = merge_hooks(settings.get("hooks"), plugin_hooks(python_command(), disabled, llm_judge),
                                    frozenset(retired_owned))
    with open(settings_path, "w", encoding="utf-8") as f:
        json.dump(settings, f, indent=2)
        f.write("\n")
    copied.append("settings.json (hooks merged; previous copy in settings.json.bak)")

    # --- 6. Stub files (full init only, never overwritten) ---
    created_stubs = []
    if not update_mode:
        stubs = {"tasks/INDEX.md": "# Task Index\n\n| Date | Task | Status | Module | Commit |\n|------|------|--------|--------|--------|\n"}
        for rel, content in stubs.items():
            path = os.path.join(claude_dir, rel)
            if not os.path.exists(path):
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
                created_stubs.append(rel)

    # --- 7. .gitignore for telemetry and self-test state ---
    gitignore_added = []
    gi_path = os.path.join(project_root, ".gitignore")
    if os.path.isfile(gi_path) or os.path.isdir(os.path.join(project_root, ".git")):
        existing = read_text(gi_path) if os.path.isfile(gi_path) else ""
        lines = {l.strip() for l in existing.splitlines()}
        missing = [l for l in GITIGNORE_LINES if l not in lines]
        if missing:
            with open(gi_path, "a", encoding="utf-8") as f:
                if existing and not existing.endswith("\n"):
                    f.write("\n")
                f.write("\n# Clauding Thought local state\n" + "\n".join(missing) + "\n")
            gitignore_added = missing

    # --- 8. Applied packs, so the generated evolve skill can diff against the originals ---
    copied_packs = []
    for pack in governance.get("packs") or []:
        name = pack.get("name") if isinstance(pack, dict) else None
        src_dir = os.path.join(plugin_root, "packs", name) if name else None
        if name and os.path.isdir(src_dir) and re.fullmatch(r"[A-Za-z0-9._-]+", name):
            dst_dir = os.path.join(claude_dir, "packs", name)
            shutil.copytree(src_dir, dst_dir, dirs_exist_ok=True)
            copied_packs.append(name)

    # --- 9. What the generated skills already know ---
    scope_heading = ((manifest.get("task_docs") or {}).get("headings") or {}).get("scope") or "Scope"
    thesis_heading = ((manifest.get("task_docs") or {}).get("headings") or {}).get("thesis") or "Thesis"
    skill_state = {
        "task_doc_has_scope": skill_text_mentions(claude_dir, "task-doc", f"## {scope_heading}"),
        "task_doc_has_thesis": skill_text_mentions(claude_dir, "task-doc", thesis_heading),
        "close_task_verifies": skill_text_mentions(claude_dir, "close-task", "/verify"),
        "evolve_reads_telemetry": skill_text_mentions(claude_dir, "evolve", "report_data.py"),
        "preflight_scores": skill_text_mentions(claude_dir, "preflight", "complexity.py"),
        "qc_forked": skill_text_mentions(claude_dir, "qc", "context: fork"),
        "qc_fix_present": os.path.isfile(os.path.join(claude_dir, "skills", "qc-fix", "SKILL.md")),
        "qc_reviewer_present": os.path.isfile(os.path.join(claude_dir, "agents", "qc-reviewer.md")),
    }

    # --- 10. Self-test ---
    selftest = run_selftest(plugin_root, project_root)

    result = {
        "status": "success" if selftest.get("status") in ("pass", "missing") else "warning",
        "mode": "update" if update_mode else "full",
        "project_root": project_root,
        "plugin_root": plugin_root,
        "plugin_version": plugin_version,
        "claude_dir": claude_dir,
        "python_command": python_command(),
        "copied": copied,
        "copied_scripts": copied_scripts,
        "copied_packs": copied_packs,
        "retired": retired,
        "left_alone": left_alone,
        "created_stubs": created_stubs,
        "gitignore_added": gitignore_added,
        "disabled_hooks": sorted(disabled),
        "unknown_disabled_hooks": unknown_disabled,
        "llm_judge_registered": llm_judge,
        "scope_heading": scope_heading,
        "thesis_heading": thesis_heading,
        "skill_state": skill_state,
        "selftest": selftest,
        "schema": os.path.join(plugin_root, "schema", "manifest.schema.json"),
        "rule_templates_dir": os.path.join(plugin_root, "rules"),
        "pattern_template": os.path.join(plugin_root, "patterns", "archetype.md"),
        "packs_dir": os.path.join(plugin_root, "packs"),
    }
    if update_mode:
        steps = []
        if selftest.get("status") not in ("pass", "missing"):
            steps.append("STOP: the hook self-test failed; show the failed rows from .claude/selftest.json and do not continue until they pass")
        steps.append("Set governance.plugin_version in .claude/manifest.json to the scaffold's plugin_version")
        if "verification" not in manifest:
            steps.append("Add a verification block to the manifest: test_command and a kind=test gate from the project's runner, claim_guard annotate, claim_window_turns 1, llm_judge false")
        if not ((manifest.get("task_docs") or {}).get("headings")):
            steps.append("Add task_docs.headings to the manifest: scope and thesis, using the headings this project's task docs already use")
        if skill_state["task_doc_has_scope"] is False or skill_state["task_doc_has_thesis"] is False:
            steps.append(f"Regenerate skills/task-doc/SKILL.md so new task docs carry `## {scope_heading}` and `## {thesis_heading}`; keep the project's other customisations")
        if skill_state["close_task_verifies"] is False:
            steps.append("Regenerate skills/close-task/SKILL.md with the pre-close checks (QC verdict present, thesis demonstrated via /verify); keep customisations")
        if skill_state["evolve_reads_telemetry"] is False:
            steps.append("Regenerate skills/evolve/SKILL.md with the telemetry and rule-hygiene steps; keep customisations")
        if skill_state["preflight_scores"] is False:
            steps.append("Regenerate skills/preflight/SKILL.md so it runs complexity.py and routes by tier; keep customisations")
        if skill_state["qc_forked"] is False:
            steps.append("Regenerate skills/qc/SKILL.md: context: fork, agent: qc-reviewer, background: false, gathers its own diff, returns only QC_VERDICT")
        if not skill_state["qc_fix_present"]:
            steps.append("Generate skills/qc-fix/SKILL.md (bounded fix-and-recheck loop)")
        if not skill_state["qc_reviewer_present"]:
            steps.append("Generate agents/qc-reviewer.md (read-only reviewer subagent)")
        if left_alone:
            steps.append("Tell the user which retired-name files were kept because the plugin did not write them: " + "; ".join(left_alone))
        steps.append("Add an [Unreleased] entry to .claude/CHANGELOG.md naming what was refreshed")
        steps.append("Report what was refreshed, what was retired, and the self-test summary")
        result["next_steps"] = steps
    else:
        result["remaining_for_agent"] = [
            ".claude/manifest.json: generate from codebase analysis (include verification and task_docs.headings)",
            ".claude/CLAUDE.md: generate governance rules from analysis",
            ".claude/CHANGELOG.md: generate the initial version entry",
            ".claude/rules/security.md: hydrate from the plugin's rules/security.md template",
            ".claude/rules/architecture.md: hydrate from the plugin's rules/architecture.md template",
            ".claude/rules/conventions.md: hydrate from the plugin's rules/conventions.md template",
            ".claude/patterns/<archetype>.md: one per sampled archetype, from patterns/archetype.md",
            ".claude/rules/<module>.md: one per module when architecture.modules has more than one entry, scoped with paths: <module path>/**",
            ".claude/agents/qc-reviewer.md: the read-only subagent the qc skill runs in",
        ] + [f".claude/skills/{s}/SKILL.md: generate project-customized" for s in GENERATED_SKILLS]

    print(json.dumps(result, indent=2))
    sys.exit(0)

except SystemExit:
    raise
except Exception as e:
    print(json.dumps({"status": "error", "error": f"{type(e).__name__}: {e}"}, indent=2))
    sys.exit(1)
